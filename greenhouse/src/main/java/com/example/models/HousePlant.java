package com.example.models; // Объявление пакета — файл лежит в src/main/java/com/example/models/

/**
 * Абстрактный базовый класс, описывающий комнатное растение.
 * <p>
 * Содержит общие характеристики всех растений: название, высоту и
 * продолжительность жизни.
 * </p>
 */
public abstract class HousePlant {
    // public    — доступен из любого пакета
    // abstract  — АБСТРАКТНЫЙ: нельзя создать объект напрямую (new HousePlant(...) — ошибка)
    //             Служит только как шаблон для наследников (Fern, Succulent, FloweringPlant)
    // class     — объявление класса

    /** Название растения. */
    private String name;
    // private — доступно только внутри класса (ИНКАПСУЛЯЦИЯ)
    // String  — тип; name — имя в camelCase
    // Никто извне не может написать plant.name = "..." — только через конструктор

    /** Высота растения в сантиметрах. */
    private double height;
    // private — инкапсуляция
    // double  — число с плавающей точкой (например, 45.5 см)

    /** Продолжительность жизни в годах. */
    private int lifespan;
    // private — инкапсуляция
    // int     — целое число (например, 7 лет)

    /**
     * Конструктор базового класса.
     *
     * @param name     название растения
     * @param height   высота в сантиметрах (должна быть положительной)
     * @param lifespan продолжительность жизни в годах (должна быть положительной)
     * @throws IllegalArgumentException если переданы некорректные значения
     */
    public HousePlant(String name, double height, int lifespan) {
        // public — конструктор доступен наследникам (при вызове super(...))
        // Валидация ДО присваивания — принцип «fail fast» (падаем сразу, а не позже)

        if (name == null || name.isBlank()) {
            // null      — проверка на отсутствие значения
            // ||        — логическое «ИЛИ»: достаточно одного истинного условия
            // isBlank() — true, если строка пустая или состоит только из пробелов

            throw new IllegalArgumentException("Название не может быть пустым");
            // throw — «бросить» исключение
            // IllegalArgumentException — неверный аргумент
            // Объект НЕ будет создан — вызывающий код получит ошибку
        }

        if (height <= 0) {
            // Высота должна быть строго положительной
            // <= 0 — отсекаем нулевую и отрицательную высоту

            throw new IllegalArgumentException("Высота должна быть > 0");
        }

        if (lifespan <= 0) {
            // Продолжительность жизни тоже строго положительная

            throw new IllegalArgumentException("Продолжительность жизни должна быть > 0");
        }

        this.name = name;
        // this.name — поле текущего объекта (private String name)
        // name      — параметр конструктора
        // this нужен, потому что имена совпадают

        this.height = height;
        // Аналогично: this.height — поле, height — параметр

        this.lifespan = lifespan;
        // this.lifespan — поле, lifespan — параметр
        // Все три поля сохранили свои значения только ПОСЛЕ успешной валидации
    }

    /**
     * @return название растения
     */
    public String getName() {
        // public    — доступен из любого пакета
        // String    — тип возврата (строка)
        // getName — геттер; нужен, потому что поле name приватное
        // @return в Javadoc описывает возвращаемое значение

        return name;
        // Возвращаем значение поля name
    }

    /**
     * @return высота растения в сантиметрах
     */
    public double getHeight() {
        // public — доступен извне
        // double — тип возврата (дробное число)

        return height;
    }

    /**
     * @return продолжительность жизни в годах
     */
    public int getLifespan() {
        // public — доступен извне
        // int    — тип возврата (целое)

        return lifespan;
    }

    /**
     * Возвращает текстовое описание растения.
     * Может быть переопределён в классах-наследниках.
     *
     * @return строка с полной информацией о растении
     */
    public String getInfo() {
        // public    — доступен всем
        // String    — тип возврата (строка)
        // НЕ abstract — есть реализация по умолчанию; наследники МОГУТ переопределить
        //               (это «точка расширения» — заготовка под полиморфизм)

        return String.format("Название: %s, высота: %.1f см, продолжительность жизни: %d лет",
                name, height, lifespan);
        // String.format(...) — статический метод, форматирует строку по шаблону
        //   %s   — подставит строку (name)
        //   %.1f — подставит double с ОДНИМ знаком после точки (height)
        //   %d   — подставит целое число (lifespan)
        // Остальной текст — литералы: "Название: ", ", высота: ", " см, продолжительность жизни: ", " лет"
        // Аргументы после шаблона идут в том же порядке, что и спецификаторы: name, height, lifespan
    }

    @Override
    public String toString() {
        // @Override — АННОТАЦИЯ: переопределяем метод из класса Object (базовый для всех классов Java)
        //             Компилятор проверит, что сигнатура совпадает с Object.toString()
        // public    — у Object.toString() тоже public, сузить нельзя
        // String    — тот же тип возврата, что у родителя

        return getInfo();
        // ДЕЛЕГИРОВАНИЕ: не дублируем логику, а вызываем getInfo()
        // Благодаря этому System.out.println(plant) напечатает красивую строку,
        // а не что-то вроде "com.example.models.Fern@1b6d3586"
    }
}